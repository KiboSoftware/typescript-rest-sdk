#!/usr/bin/env node
/**
 * generate.mjs - regenerate src/clients/ from the docs repo's SDK specs
 *
 * Usage:
 *   node generator/generate.mjs --specs <dir>            regenerate every client
 *   node generator/generate.mjs --specs <dir> --client Commerce   just one
 *   node generator/generate.mjs --specs <dir> --check    fail if output differs
 *
 * <dir> is a checkout of unified-documentation's openapi-pipeline/dist_sdk,
 * which contains one spec per client plus manifest.json. Those specs are the
 * published Kibo API docs with operationIds preserved; see that repo's
 * openapi-pipeline/README.md for how they are produced.
 *
 * What this script owns, beyond invoking the generator:
 *
 *   - Regenerating only the directories openapi-generator produces
 *     (apis/, models/, index.ts, runtime.ts). src/client-runtime, src/types and
 *     src/utilities are hand-written and must survive.
 *   - Writing api-path.ts per client. It is not generated by any template, but
 *     every generated API class imports basePathTemplate from it, so a client
 *     regenerated without it will not compile.
 *   - Deleting client directories that no longer appear in the manifest, so a
 *     removed service does not linger as stale code.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLIENTS_DIR = path.join(REPO_ROOT, 'src', 'clients');
const CONFIG_PATH = path.join(REPO_ROOT, 'generator', 'config.yaml');
const JAR_DIR = path.join(REPO_ROOT, 'generator', '.jar');

// Pinned deliberately. The committed SDK was produced by 6.2.0, and later
// majors change the typescript-fetch output shape (notably how request
// parameters and nullable types are emitted), which would rename or retype
// public API surface. Upgrading is a deliberate, reviewed change.
const GENERATOR_VERSION = '6.2.0';
const GENERATOR_URL =
  `https://repo1.maven.org/maven2/org/openapitools/openapi-generator-cli/` +
  `${GENERATOR_VERSION}/openapi-generator-cli-${GENERATOR_VERSION}.jar`;

// Matches the invocation the original sdk-generator-poc used. Each flag is
// load-bearing:
//   prefixParameterInterfaces  request interfaces are named per API class, so
//                              two clients can both define a GetRequest
//   withoutRuntimeChecks       no per-model FromJSON/ToJSON validators; the SDK
//                              deserializes without runtime type checking
//   withInterfaces=false       no separate FooApiService interface per class
//   supportsES6=false          CommonJS-compatible output
const ADDITIONAL_PROPERTIES = [
  'prefixParameterInterfaces=true',
  'hideGenerationTimestamp=true',
  'withoutRuntimeChecks=true',
  'withInterfaces=false',
  'supportsES6=false',
].join(',');

// Everything openapi-generator writes into a client directory. Anything else in
// there is hand-maintained and is left alone.
const GENERATED_ENTRIES = ['apis', 'models', 'index.ts', 'runtime.ts', '.openapi-generator', '.openapi-generator-ignore'];

// A sibling checkout is the usual layout; --specs overrides it.
const DEFAULT_SPECS_DIR = path.resolve(REPO_ROOT, '..', 'unified-documentation', 'openapi-pipeline', 'dist_sdk');

function parseArgs(argv) {
  const args = { client: null, check: false, specs: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--client') args.client = argv[++i];
    else if (argv[i] === '--specs') args.specs = argv[++i];
    else if (argv[i] === '--check') args.check = true;
  }
  return args;
}

function ensureGeneratorJar() {
  const jarPath = path.join(JAR_DIR, `openapi-generator-cli-${GENERATOR_VERSION}.jar`);
  if (fs.existsSync(jarPath)) return jarPath;

  fs.mkdirSync(JAR_DIR, { recursive: true });
  console.log(`Downloading openapi-generator ${GENERATOR_VERSION}...`);
  execFileSync('curl', ['-sSLf', '-o', jarPath, GENERATOR_URL], { stdio: 'inherit' });
  return jarPath;
}

function requireJava() {
  try {
    execFileSync('java', ['-version'], { stdio: 'pipe' });
  } catch {
    console.error('Java is required to run openapi-generator. Install a JDK (11 or newer) and retry.');
    process.exit(2);
  }
}

/**
 * Remove only the generated parts of a client directory.
 *
 * A plain rm -rf of the client would take api-path.ts with it, and every
 * generated API class imports basePathTemplate from that file.
 */
function clearGenerated(clientDir) {
  for (const entry of GENERATED_ENTRIES) {
    fs.rmSync(path.join(clientDir, entry), { recursive: true, force: true });
  }
}

function generateClient(jarPath, client, specsDir) {
  const specPath = path.join(specsDir, client.specFile);
  const outDir = path.join(CLIENTS_DIR, client.name);

  if (!fs.existsSync(specPath)) {
    throw new Error(`spec not found: ${specPath}`);
  }

  fs.mkdirSync(outDir, { recursive: true });
  clearGenerated(outDir);

  execFileSync(
    'java',
    [
      '-jar', jarPath,
      'generate',
      '-c', CONFIG_PATH,
      '-g', 'typescript-fetch',
      '-i', specPath,
      '-o', outDir,
      // The specs are intentionally not strictly valid: they carry Kibo's
      // editorial overlays and a handful of upstream quirks the docs pipeline
      // does not rewrite. Validation is enforced in the docs repo instead.
      '--skip-validate-spec',
      `--additional-properties=${ADDITIONAL_PROPERTIES}`,
    ],
    { cwd: REPO_ROOT, stdio: ['ignore', 'pipe', 'pipe'] }
  );

  // Not produced by any template, but imported by every generated API class.
  fs.writeFileSync(
    path.join(outDir, 'api-path.ts'),
    `export const basePathTemplate = '${client.basePathTemplate}'`,
    'utf8'
  );
}

/**
 * Delete client directories that are no longer in the manifest.
 */
function pruneRemovedClients(manifest) {
  if (!fs.existsSync(CLIENTS_DIR)) return [];
  const expected = new Set(manifest.clients.map((c) => c.name));
  const removed = [];

  for (const entry of fs.readdirSync(CLIENTS_DIR)) {
    const dir = path.join(CLIENTS_DIR, entry);
    if (!fs.statSync(dir).isDirectory() || expected.has(entry)) continue;
    fs.rmSync(dir, { recursive: true, force: true });
    removed.push(entry);
  }

  return removed;
}

function main() {
  const args = parseArgs(process.argv.slice(2));

  const specsDir = path.resolve(args.specs || DEFAULT_SPECS_DIR);
  if (!fs.existsSync(specsDir)) {
    console.error(
      `No specs at ${specsDir}.\n` +
        'Pass --specs <dir> pointing at unified-documentation/openapi-pipeline/dist_sdk, ' +
        'or check that repo out next to this one.'
    );
    process.exit(2);
  }
  const manifestPath = path.join(specsDir, 'manifest.json');
  if (!fs.existsSync(manifestPath)) {
    console.error(`No manifest.json in ${specsDir}. Run 'npm run spec:sdk-build' in the docs repo first.`);
    process.exit(2);
  }

  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
  requireJava();
  const jarPath = ensureGeneratorJar();

  const clients = args.client
    ? manifest.clients.filter((c) => c.name === args.client)
    : manifest.clients;

  if (!clients.length) {
    console.error(`No client named '${args.client}' in the manifest.`);
    process.exit(2);
  }

  console.log(`Generating ${clients.length} client(s) from ${specsDir}\n`);

  const failures = [];
  for (const client of clients) {
    process.stdout.write(`  ${client.name.padEnd(24)}`);
    try {
      generateClient(jarPath, client, specsDir);
      console.log(`${String(client.operations).padStart(4)} ops, ${String(client.schemas).padStart(4)} models`);
    } catch (error) {
      console.log('FAILED');
      failures.push({ name: client.name, error: error.stderr?.toString() || error.message });
    }
  }

  // Pruning only makes sense on a full run; a single-client run has no view of
  // which other clients are still current.
  if (!args.client) {
    for (const name of pruneRemovedClients(manifest)) {
      console.log(`  removed client no longer in the manifest: ${name}`);
    }
  }

  if (failures.length) {
    console.error(`\n${failures.length} client(s) failed to generate:\n`);
    for (const f of failures) console.error(`  ${f.name}: ${f.error.split('\n').slice(-6).join('\n')}`);
    process.exit(1);
  }

  console.log('\nGeneration complete. Next: npm run build && npm test');

  if (args.check) {
    const diff = execFileSync('git', ['status', '--porcelain', 'src/clients'], {
      cwd: REPO_ROOT,
      encoding: 'utf8',
    });
    if (diff.trim()) {
      console.error('\n--check: generated output differs from the committed tree:\n');
      console.error(diff);
      process.exit(1);
    }
    console.log('--check: generated output matches the committed tree');
  }
}

main();
